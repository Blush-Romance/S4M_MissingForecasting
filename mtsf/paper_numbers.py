def best_reported(pattern, dataset, seq_len, metric=0):
    """Best (lowest) value over all methods reported in the S4M paper."""
    rows = PAPER[pattern][dataset][seq_len]
    vals = [(v[metric], k) for k, v in rows.items() if v[metric] is not None]
    return min(vals)
